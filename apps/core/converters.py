"""
مبدل آدرس برای اسلاگ‌های فارسی.

مشکل: مبدل آماده Django به نام slug فقط حروف انگلیسی را می‌پذیرد
(الگویش [-a-zA-Z0-9_]+ است). ولی در مدل‌های ما slug با allow_unicode=True
تعریف شده تا ادمین بتواند آدرس فارسی هم بسازد؛ مثلاً:

    /courses/ایمنی-صنعتی/

اگر از مبدل پیش‌فرض استفاده کنیم، چنین آدرسی اصلاً به View نمی‌رسد و
کاربر صفحه ۴۰۴ می‌بیند، در حالی که دوره واقعاً وجود دارد.

راه‌حل: یک مبدل ساده که همان الگو را با پشتیبانی از یونیکد تعریف می‌کند.
در پایتون ۳، \\w به‌صورت پیش‌فرض حروف فارسی را هم شامل می‌شود.
"""


class UnicodeSlugConverter:
    """مثل مبدل slug، اما حروف غیرانگلیسی را هم می‌پذیرد."""

    regex = r"[-\w]+"

    def to_python(self, value: str) -> str:
        return value

    def to_url(self, value: str) -> str:
        return value
