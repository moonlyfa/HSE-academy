#!/usr/bin/env bash
# =============================================================================
#  پشتیبان‌گیری آکادمی HSE
#  ---------------------------------------------------------------------------
#  سه چیز پشتیبان گرفته می‌شود و هر سه لازم‌اند:
#
#     ۱. دیتابیس            ← کاربران، سفارش‌ها، ثبت‌نام‌ها، کارنامه‌ها، گواهی‌ها
#     ۲. media/             ← تصویر دوره‌ها، لوگو، اسلایدها
#     ۳. protected_media/   ← ویدیو و جزوه دوره‌ها (سنگین‌ترین بخش)
#
#  بدون مورد سوم، پشتیبان شما یک سایت بدون محتواست؛ بدون مورد اول، محتوا
#  هست اما معلوم نیست مال چه کسی.
#
#  اجرای دستی:   sudo -u hse /srv/hse/deploy/backup.sh
#  اجرای خودکار: با systemd timer (deploy/hse-backup.timer)
# =============================================================================

set -euo pipefail

PROJECT_DIR="${PROJECT_DIR:-/srv/hse}"
BACKUP_DIR="${BACKUP_DIR:-/var/backups/hse}"
KEEP_DAYS="${KEEP_DAYS:-14}"

STAMP="$(date +%Y-%m-%d_%H%M)"
TARGET="${BACKUP_DIR}/${STAMP}"

mkdir -p "${TARGET}"

echo "پشتیبان‌گیری در ${TARGET}"

# --- ۱. دیتابیس ---------------------------------------------------------
# مقدار DATABASE_URL از همان فایل .env خوانده می‌شود که خود سایت می‌خواند،
# تا هیچ‌وقت پشتیبان از دیتابیس اشتباهی گرفته نشود.
DATABASE_URL="$(grep -E '^DATABASE_URL=' "${PROJECT_DIR}/.env" | cut -d= -f2- || true)"

if [[ -z "${DATABASE_URL}" ]]; then
    echo "DATABASE_URL در .env پیدا نشد — پشتیبان دیتابیس گرفته نشد." >&2
    exit 1
fi

# --format=custom امکان بازگردانی انتخابی (مثلاً فقط یک جدول) را می‌دهد و
# خودش هم فشرده است.
pg_dump --dbname="${DATABASE_URL}" --format=custom --file="${TARGET}/database.dump"
echo "  ✓ دیتابیس"

# --- ۲ و ۳. فایل‌ها ------------------------------------------------------
tar --create --gzip \
    --file="${TARGET}/media.tar.gz" \
    --directory="${PROJECT_DIR}" media
echo "  ✓ فایل‌های عمومی"

tar --create --gzip \
    --file="${TARGET}/protected_media.tar.gz" \
    --directory="${PROJECT_DIR}" protected_media
echo "  ✓ فایل‌های محافظت‌شده"

# --- فایل تنظیمات -------------------------------------------------------
# .env کلیدهای درگاه و پیامک را دارد. بدون آن، بازگردانی یعنی از نو ساختن
# همه کلیدها. دسترسی فایل پشتیبان محدود می‌شود.
cp "${PROJECT_DIR}/.env" "${TARGET}/env.backup"
chmod 600 "${TARGET}/env.backup"
echo "  ✓ فایل تنظیمات"

# --- پاک کردن پشتیبان‌های قدیمی ----------------------------------------
find "${BACKUP_DIR}" -mindepth 1 -maxdepth 1 -type d -mtime "+${KEEP_DAYS}" \
     -exec rm -rf {} +

SIZE="$(du -sh "${TARGET}" | cut -f1)"
echo "پشتیبان کامل شد (${SIZE}). نگهداری: ${KEEP_DAYS} روز."

# =============================================================================
#  هشدار مهم
#  ---------------------------------------------------------------------------
#  پشتیبانی که روی همان سرور بماند، پشتیبان نیست: اگر دیسک سرور بسوزد یا
#  سرور پاک شود، پشتیبان هم با آن می‌رود. حتماً یک نسخه را بیرون از سرور
#  ببرید (مثلاً با rclone یا rsync روی فضای ابری یا کامپیوتر دفتر).
#
#  و مهم‌تر: **پشتیبان امتحان‌نشده، پشتیبان نیست.** هر چند ماه یک‌بار روی
#  یک سرور آزمایشی بازگردانی کنید. روش بازگردانی در docs/deployment.md
#  نوشته شده است.
# =============================================================================
